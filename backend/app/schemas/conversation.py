"""
Schemas for Conversation History, Context Management, and SLM Integration.
"""

from __future__ import annotations

from typing import Any
from pydantic import BaseModel, Field


class SLMProposal(BaseModel):
    """
    Structured intent proposal generated by the Small Language Model (SLM).
    The backend decision engine strictly validates this before execution.
    """
    intent: str = Field(..., description="Proposed intent category")
    target_device: str | None = Field(default=None, description="Proposed target device ID")
    requested_action: str | None = Field(default=None, description="Proposed action (ON, OFF, etc.)")
    context_used: dict[str, Any] = Field(default_factory=dict, description="Context features utilized")
    confidence: float = Field(default=0.0, description="Estimated confidence 0.0 - 1.0")
    uncertainty_score: float = Field(default=0.0, description="Model uncertainty 0.0 - 1.0")
    requires_clarification: bool = Field(default=False, description="Whether the SLM flagged ambiguity")
    clarification_prompt: str | None = Field(default=None, description="Suggested question if ambiguous")
    reason: str = Field(default="", description="Chain-of-thought or explanation for proposal")
    model_name: str = Field(default="local-semantic-slm", description="SLM model identifier")
    latency_ms: float = Field(default=0.0, description="Inference latency in milliseconds")


class ConversationTurn(BaseModel):
    """A single turn in the conversation history."""
    id: int
    session_id: str
    timestamp: str
    user_text: str | None = None
    assistant_response: str | None = None
    intent: str | None = None
    device_id: str | None = None
    action: str | None = None
    decision_outcome: str | None = None
    execution_status: str | None = None
    is_clarification: bool = False
    clarification_question: str | None = None
    clarification_answer: str | None = None
    is_follow_up: bool = False


class ConversationHistoryResponse(BaseModel):
    """Paginated or bounded conversation history for a session."""
    session_id: str
    total_turns: int
    max_limit: int
    turns: list[ConversationTurn] = []


class ContextSummaryResponse(BaseModel):
    """Summary of active context and device states for a session."""
    session_id: str
    last_device: str | None = None
    last_device_type: str | None = None
    last_action: str | None = None
    last_command: str | None = None
    has_pending_clarification: bool = False
    pending_clarification_question: str | None = None
    pending_action: str | None = None
    current_device_states: dict[str, str] = {}

